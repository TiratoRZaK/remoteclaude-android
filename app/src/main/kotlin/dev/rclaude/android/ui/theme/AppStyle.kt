package dev.rclaude.android.ui.theme

/**
 * Оформление приложения: набор шрифтов, палитры, скруглений, фона и раскраски
 * терминала. Выбирается в настройках и хранится в DataStore по [id].
 */
enum class AppStyle(val id: String, val title: String, val tagline: String) {

    /** Фосфорная зелень на смоле, всё моноширинным. */
    NIGHT_TERMINAL("night-terminal", "Ночной терминал", "Фосфорная зелень на смоле, всё моноширинным"),

    /** Тёплая бумага, антиква и рыжие чернила. */
    PAPER_INK("paper-ink", "Бумага и чернила", "Тёплая бумага, антиква и рыжие чернила"),

    /** Неон восьмидесятых, лиловый градиент и широкие заголовки. */
    SYNTHWAVE("synthwave", "Синтвейв", "Неон восьмидесятых и лиловый градиент"),

    /** Холодный сланец с бирюзовым свечением. */
    AURORA("aurora", "Северное сияние", "Холодный сланец с бирюзовым свечением"),

    /** Эспрессо, сливки и рукописная вывеска. */
    COFFEE("coffee", "Кофейня", "Эспрессо, сливки и рукописная вывеска"),

    /** Пиксельный шрифт, жёлтый на индиго, ноль скруглений. */
    ARCADE("arcade", "Аркада", "Пиксельный шрифт и жёлтый на индиго"),

    /** Пергамент, сепия и уставная вязь. */
    CHRONICLE("chronicle", "Летопись", "Пергамент, сепия и уставная вязь"),
    ;

    companion object {

        /** Оформление по умолчанию. */
        val DEFAULT: AppStyle = NIGHT_TERMINAL

        /** Находит оформление по сохранённому идентификатору. */
        fun fromId(id: String?): AppStyle = entries.firstOrNull { it.id == id } ?: DEFAULT
    }
}
